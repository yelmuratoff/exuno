//! `tests/release.bats`: `exuno release` — bumps VERSION, Cargo.toml, and
//! Cargo.lock together, commits, tags, and (unless `--no-push`) pushes. Every
//! case runs against its own temp checkout; nothing here touches the real
//! repository or pushes anywhere but a throwaway bare remote.

mod common;

use std::path::Path;
use std::process::Command as StdCommand;

use common::Project;
use predicates::prelude::*;

/// The version `release <bump>` writes from the seed's VERSION.
fn seed_version() -> &'static str {
    include_str!("../VERSION").trim()
}

fn bumped(bump: &str) -> String {
    let parts: Vec<u64> = seed_version()
        .split('.')
        .map(|p| p.parse().unwrap())
        .collect();
    let (major, minor, patch) = (parts[0], parts[1], parts[2]);
    match bump {
        "major" => format!("{}.0.0", major + 1),
        "minor" => format!("{major}.{}.0", minor + 1),
        "patch" => format!("{major}.{minor}.{}", patch + 1),
        other => panic!("unknown bump: {other}"),
    }
}

/// A minimal checkout `release` accepts: VERSION, Cargo.toml, Cargo.lock, and
/// a CHANGELOG with a patch section, committed on `main`.
fn checkout() -> Project {
    let project = Project::empty();
    project.git(&["symbolic-ref", "HEAD", "refs/heads/main"]);
    let version = seed_version();
    project.write("VERSION", &format!("{version}\n"));
    project.write(
        "Cargo.toml",
        &format!(
            "[package]\nname = \"exuno\"\nversion = \"{version}\"\nedition = \"2024\"\n\n[dependencies]\nclap = {{ version = \"4.6\", features = [\"derive\"] }}\n"
        ),
    );
    project.write(
        "Cargo.lock",
        &format!(
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"exuno\"\nversion = \"{version}\"\ndependencies = [\n \"clap\",\n]\n\n[[package]]\nname = \"clap\"\nversion = \"4.6.0\"\n"
        ),
    );
    project.write(
        "CHANGELOG.md",
        &format!(
            "# Changelog\n\n## {}\n\nA patch.\n\n- one fix\n\n## {version}\n\nThe seed.\n",
            bumped("patch")
        ),
    );
    project.git(&["add", "-A"]);
    project.git(&["commit", "-m", "seed", "--quiet"]);
    project
}

fn absent_git_config() -> std::path::PathBuf {
    std::env::temp_dir().join("agentsync-tests-absent-gitconfig")
}

/// `git <args>` in an arbitrary directory (the bare remote), isolated from
/// the developer's global config the same way `common::Project::git` is.
fn git_in(dir: &Path, args: &[&str]) -> String {
    let output = StdCommand::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_CONFIG_GLOBAL", absent_git_config())
        .env("GIT_CONFIG_SYSTEM", absent_git_config())
        .output()
        .unwrap();
    assert!(output.status.success(), "git {args:?} failed in {dir:?}");
    String::from_utf8(output.stdout).unwrap()
}

#[test]
fn release_patch_bumps_version() {
    let project = checkout();
    project
        .exuno()
        .args(["release", "patch", "--no-push"])
        .write_stdin("y\n")
        .assert()
        .success();
    assert_eq!(project.read("VERSION"), format!("{}\n", bumped("patch")));
}

