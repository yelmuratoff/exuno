#[test]
fn release_fails_when_cargo_lock_has_no_agentsync_entry_and_writes_nothing() {
    let project = checkout();
    project.write("Cargo.lock", "version = 4\n");
    project.git(&["commit", "-qam", "lock without agentsync"]);
    project
        .exuno()
        .args(["release", "patch", "--no-push"])
        .write_stdin("y\n")
        .assert()
        .code(1)
        .stderr(predicate::str::contains(
            "Cannot find the exuno crate version in Cargo.lock",
        ))
        .stdout(predicate::str::contains("Continue?").not());
    assert_eq!(project.read("VERSION"), format!("{}\n", seed_version()));
    assert_eq!(git_in(project.path(), &["status", "--porcelain"]), "");
}

