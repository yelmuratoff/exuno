#[test]
fn release_commits_version_cargo_toml_and_cargo_lock_together() {
    let project = checkout();
    project
        .exuno()
        .args(["release", "patch", "--no-push"])
        .write_stdin("y\n")
        .assert()
        .success();
    let names = git_in(
        project.path(),
        &["show", "--format=", "--name-only", "HEAD"],
    );
    let mut files: Vec<&str> = names.lines().collect();
    files.sort_unstable();
    assert_eq!(files, ["Cargo.lock", "Cargo.toml", "VERSION"]);
    assert_eq!(git_in(project.path(), &["status", "--porcelain"]), "");
}

